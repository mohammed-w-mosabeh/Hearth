func msg(key string) string {
	if s, ok := en[key]; ok {
		return s
	}
	return key
}

func kindLabel(kind string) string {
	if s, ok := en["kind."+kind]; ok {
		return s
	}
	return kind
}

// fmtBytes formats n bytes with binary units, like the UI.
func fmtBytes(n float64) string {
	neg := n < 0
	n = math.Abs(n)
	units := []string{"B", "KiB", "MiB", "GiB", "TiB", "PiB"}
	i := 0
	for n >= 1024 && i < len(units)-1 {
		n /= 1024
		i++
	}
	s := strconv.FormatFloat(n, 'f', 1, 64)
	if i == 0 {
		s = strconv.FormatFloat(n, 'f', 0, 64)
	}
	if neg {
		s = "−" + s
	}
	return s + " " + units[i]
}

func fmtSigned(n float64) string {
	if n > 0 {
		return "+" + fmtBytes(n)
	}
	return fmtBytes(n)
}

func fmtNum(v float64, digits int) string { return strconv.FormatFloat(v, 'f', digits, 64) }

// fmtValue formats v in unit.
func fmtValue(v float64, unit string) string {
	switch unit {
	case "%":
		return fmtNum(v, 1) + " %"
	case "°C":
		return fmtNum(v, 0) + " °C"
	case "bytes":
		return fmtBytes(v)
	case "bytes/s":
		return fmtBytes(v) + "/s"
	}
	return fmtNum(v, 2)
}

func fmtTime(t time.Time) string { return t.Local().Format("2006-01-02 15:04") }

func fmtMs(ms int64) string { return fmtTime(time.UnixMilli(ms)) }

// fmtCPUTime formats CPU time given in hours of the whole machine.
func fmtCPUTime(machineHours float64) string {
	d := time.Duration(machineHours * float64(time.Hour))
	switch {
	case d >= time.Hour:
		return fmt.Sprintf("%dh %02dm", int(d.Hours()), int(d.Minutes())%60)
	case d >= time.Minute:
		return fmt.Sprintf("%dm %02ds", int(d.Minutes()), int(d.Seconds())%60)
	}
	return fmt.Sprintf("%ds", int(d.Seconds()))
}

// eventWhat is "Package upgraded", "Unit added", or a Hearth action.
func eventWhat(e changes.Event) string {
	if e.Source == changes.SourceHearth {
		return msg("src.hearth") + ": " + e.Action
	}
	return msg("src."+e.Source) + " " + msg("ev."+e.Kind)
}

// eventDetail is "1.0 → 1.1", a value, or an action's origin and result.
func eventDetail(e changes.Event) string {
	switch {
	case e.Source == changes.SourceHearth:
		return e.Result + " (" + e.Origin + ")"
	case e.Before != "" && e.After != "":
		return e.Before + " → " + e.After
	}
	return e.Before + e.After
}

func statusLabel(s string) string { return msg("status." + s) }

// findingTexts lists a check's findings in English.
func findingTexts(c posture.Check) []string {
	out := make([]string, 0, len(c.Findings)+1)
	for _, f := range c.Findings {
		out = append(out, posture.Text(f))
	}
	if c.Error != "" {
		out = append(out, c.Error)
	}
	return out
}

func periodLabel(p string) string { return msg("period." + p) }

// alertValue formats an alert's peak in its metric's unit ("" for states
// such as "unit failed", which have no value worth showing).
func alertValue(metric string, v float64) string {
	for _, m := range alerts.Metrics {
		if m.ID == metric {
			if m.Unit == "" {
				return ""
			}
			return fmtValue(v, m.Unit)
		}
	}
	return fmtNum(v, 1)
}

func fmtEnded(e *int64) string {
	if e == nil {
		return msg("ongoing")
	}
	return fmtMs(*e)
}

func fmtCovered(c float64) string { return fmtNum(c*100, 0) + " %" }

// oneLine flattens a system-derived string for a table cell or heading.
func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
