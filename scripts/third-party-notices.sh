#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.md: the licence of everything that ships in
# Hearth's binaries, read from the Go module cache and web/node_modules,
# never typed by hand. With --check it fails if the file is out of date.
#
# What ships: the Go modules linked into cmd/... (go list -deps), the Go
# standard library, the npm packages bundled into the UI (the production
# dependencies and Svelte's runtime) and the fonts in web/src/assets/fonts.
# The icons are drawn in web/src/components/Icon.svelte; there is no icon set.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

licence_file() { # prints the first licence file in directory $1
	local f
	for f in LICENSE LICENSE.txt LICENSE.md LICENCE LICENCE.txt LICENSE-MIT COPYING COPYING.txt license license.txt license.md; do
		if [[ -f $1/$f ]]; then
			echo "$1/$f"
			return 0
		fi
	done
	echo "third-party-notices: no licence file in $1" >&2
	return 1
}

section() { # name, version, url, licence file
	{
		printf '\n---\n\n## %s %s\n\n%s\n\n```\n' "$1" "$2" "$3"
		sed -e 's/[[:space:]]*$//' "$4" | tr -d '\r'
		printf '```\n'
	} >>"$tmp"
}

{
	echo '# Third-party notices'
	echo
	echo 'Hearth is licensed under the Apache License 2.0 (see `LICENSE`). Its binaries include the software and fonts below, each under its own licence. This file is generated by `scripts/third-party-notices.sh`; do not edit it.'
	echo
	echo 'The icons are drawn for Hearth (`web/src/components/Icon.svelte`); no icon set is included.'
} >"$tmp"

echo >>"$tmp"
echo '# Go' >>"$tmp"
goroot=$(go env GOROOT)
section "Go standard library and runtime" "$(go env GOVERSION)" "https://go.dev" "$goroot/LICENSE"
self=$(go list -m)
go list -deps -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' ./cmd/... | sort -u |
	while read -r path version dir; do
		[[ $path == "$self" ]] && continue
		section "$path" "$version" "https://pkg.go.dev/$path@$version" "$(licence_file "$dir")"
	done

echo >>"$tmp"
echo '# npm (bundled into the UI)' >>"$tmp"
# Svelte is a build dependency whose runtime is compiled into the bundle.
pkgs=$(jq -r '.dependencies | keys[]' web/package.json)
for p in $pkgs svelte; do
	dir=web/node_modules/$p
	[[ -d $dir ]] || { echo "third-party-notices: run 'make web' first ($dir is missing)" >&2; exit 1; }
	section "$p" "$(jq -r .version "$dir/package.json")" "https://www.npmjs.com/package/$p" "$(licence_file "$dir")"
done
if [[ -n $(cd web && npm ls --omit=dev --all --parseable 2>/dev/null | tail -n +2 | sed 's|.*node_modules/||' | grep -vxF -e "$pkgs" || true) ]]; then
	echo "third-party-notices: a production npm dependency has dependencies of its own; list them here" >&2
	exit 1
fi

echo >>"$tmp"
echo '# Fonts' >>"$tmp"
section "IBM Plex Sans and IBM Plex Sans Arabic" "1.1.0" "https://github.com/IBM/plex (see web/src/assets/fonts/README.md)" web/src/assets/fonts/LICENSE.txt
section "JetBrains Mono" "(Latin subset, see web/src/assets/fonts/README.md)" "https://github.com/JetBrains/JetBrainsMono" web/src/assets/fonts/LICENSE-JetBrainsMono.txt

if [[ ${1:-} == --check ]]; then
	if ! cmp -s "$tmp" "$out"; then
		echo "third-party-notices: $out is out of date; run 'make notices'" >&2
		exit 1
	fi
	echo "third-party-notices: up to date"
	exit 0
fi
cp "$tmp" "$out"
echo "wrote $out ($(wc -l <"$out") lines)"
